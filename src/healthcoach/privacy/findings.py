"""Безопасный вид находки — один на все пути наружу.

Находка собирается из двух источников: базы знаний коуча и бланка клиента.
Первый безопасен, второй — нет: в бланк попадает что угодно, вплоть до
имени клиента, номера страховки и телефона лаборатории, а на ручном вводе
коуч набирает подпись единиц дословно. Наружу — модели и клиенту — уходит
только то, что прошло через `safe_finding`.

Маска стояла в двух местах и уже разошлась: `llm/payload.py` закрывал
заголовок, единицы и заметку, а `report/data.py` — только заголовок, и
единицы с бланка доходили до отчёта дословно. Пока их не печатали, это
было незаметно. Поэтому правило записано здесь один раз, а оба пути его
ввозят: разойтись дальше нечему.

Модуль лежит в `privacy`, а не в `llm`: клиентский отчёт не должен
импортировать сборку входа модели ради константы, а `privacy` уже про то,
что наружу не выпускается.
"""

from __future__ import annotations

from dataclasses import replace

from healthcoach.scoring.findings import Finding

UNRESOLVED_TITLE = "показатель из бланка, не распознан"
"""Заголовок находки, чей настоящий title списан с бланка клиента
(`measurement.label`, иногда OCR-ом с фотографии) и может содержать что
угодно, вплоть до имени клиента. Модель всё равно не может истолковать
показатель, которого нет в базе знаний, поэтому общая формулировка
ничего не теряет.

Маскируется ровно то, что помечено `title_from_document`, — и ничего
больше. `rule_missing` для этой роли не годится: он поднят на четырёх
разных путях, а заголовок из документа приходит только с одного
(`scoring/references.py`, `_unresolved`). На трёх остальных — единицы не
сопоставлены, нет целевого значения для пола и возраста, производный не
посчитан — заголовок это `analyte.name`/`derived.name` из базы знаний
коуча. Раздел «показатели» обязан такие находки назвать, а под маской
назвать их нечем. Заголовок опросника из документа не приходит никогда."""

DOCUMENT_UNITS = "единицы из бланка"
"""Чем заменяются единицы, списанные с бланка. Ручной ввод сохраняет их
дословно, так что маска на заголовке без маски на единицах не закрывает
строку: `units` и отголосок исходного написания в `note` идут в той же
строке, что и заголовок."""


def safe_finding(finding: Finding) -> Finding:
    """Находка, из которой убрано всё, чего клиенту и модели видеть нельзя.

    Три правила, и все три — про источник текста, а не про статус:

    * `title_from_document` — заголовок списан с бланка, наружу идёт общая
      формулировка;
    * `units_from_document` — единицы списаны с бланка; вместе с ними
      снимается и заметка: на этом пути она пересказывает исходное
      написание («измерение пришло в …»), то есть проносит текст документа
      мимо маски. Статус («единицы не сопоставлены») остаётся — и модель,
      и коуч по нему видят, что показатель не истолкован;
    * `note_private` — заметка написана коучем для коуча и может звать к
      конкретному врачу с фамилией и телефоном. Наружу она не идёт по той
      же причине, по которой `Specialists.public_view()` вычёркивает врачей.

    Значение, статус, целевой коридор и лабораторный интервал не трогаются:
    это числа, посчитанные кодом, и ради них отчёт и собирается.
    """
    title = UNRESOLVED_TITLE if finding.title_from_document else finding.title
    units = DOCUMENT_UNITS if finding.units_from_document else finding.units
    note = (
        None
        if finding.units_from_document or finding.note_private
        else finding.note
    )
    if (title, units, note) == (finding.title, finding.units, finding.note):
        return finding
    return replace(finding, title=title, units=units, note=note)
