"""Словарь степеней отклонения.

Общий источник для валидатора спецификации опросника и для сортировки
находок по значимости: два независимых списка названий уже расходились
однажды. Женские формы — для блоков опросника («степень отклонения»),
мужские — для DASS («показатель»).
"""

from __future__ import annotations

DEGREE_ORDER = (
    "нормальный",
    "низкая",
    "средняя",
    "средний",
    "умеренная",
    "умеренный",
    "высокая",
    "тяжелая",
    "тяжелый",
    "очень тяжелая",
    "очень тяжелый",
)
"""Степени от лёгкой к тяжёлой, в нормализованном виде."""

_DEGREE_INDEX = {name: i for i, name in enumerate(DEGREE_ORDER)}


def normalize_degree(degree: str) -> str:
    """Привести название степени к виду, в котором оно ищется в порядке."""
    return degree.strip().casefold().replace("ё", "е")


def degree_rank(degree: str) -> int | None:
    """Позиция степени в порядке, либо None если название незнакомо."""
    return _DEGREE_INDEX.get(normalize_degree(degree))


DEGREE_SEVERITY = {
    "нормальный": 3,
    "низкая": 2,
    "средняя": 1,
    "средний": 1,
    "умеренная": 1,
    "умеренный": 1,
    "высокая": 0,
    "тяжелая": 0,
    "тяжелый": 0,
    "очень тяжелая": 0,
    "очень тяжелый": 0,
}
"""Тяжесть степени для сортировки находок: 0 — требует внимания, 3 — норма.

Отдельно от DEGREE_ORDER, потому что задачи разные: порядок нужен валидатору,
чтобы ловить пересечения и разрывы между диапазонами соседних степеней,
а тяжесть огрублена и в ней есть совпадения — вывести одно из другого нельзя.
Род на тяжесть не влияет: обе формы дают один уровень.
"""


def degree_severity(degree: str) -> int | None:
    """Тяжесть степени, либо None если название незнакомо."""
    return DEGREE_SEVERITY.get(normalize_degree(degree))
